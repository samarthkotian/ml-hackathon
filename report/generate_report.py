def _img(path: str, width_in: float = 6.3, max_height_in: float = 4.1):
    """Create a proportionally scaled ReportLab Image flowable."""
    if not os.path.exists(path):
        return Paragraph(f"<i>[Figure missing: {os.path.basename(path)}]</i>", getSampleStyleSheet()["Normal"])
    from matplotlib import image as mpimg
    arr = mpimg.imread(path)
    h_px, w_px = arr.shape[:2]
    aspect = h_px / max(1.0, float(w_px))
    w = width_in * inch
    h = w * aspect
    if h > max_height_in * inch:
        h = max_height_in * inch
        w = h / aspect
    im = Image(path, width=w, height=h)
    im.hAlign = "CENTER"
    return im


def _styled_table(data, col_widths=None, font_size=8.0):
    hdr_style = ParagraphStyle(
        "TblHdr",
        fontName="Helvetica-Bold",
        fontSize=font_size - 0.3,
        leading=font_size + 1.4,
        textColor=colors.white,
        alignment=1,
    )
    formatted_data = []
    for r_i, row in enumerate(data):
        if r_i == 0:
            formatted_data.append(
                [Paragraph(str(c), hdr_style) if isinstance(c, str) else c for c in row]
            )
        else:
            formatted_data.append(row)

    t = Table(formatted_data, colWidths=col_widths, repeatRows=1)
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, 0), font_size),
                ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
                ("FONTSIZE", (0, 1), (-1, -1), font_size),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("TOPPADDING", (0, 0), (-1, -1), 3.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
                ("LEFTPADDING", (0, 0), (-1, -1), 3.5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 3.5),
            ]
        )
    )
    return t


